def reader_validator_node(state: AppState) -> AppState:
    print("--- Reader & Validator Node ---")
    file_path = state.get('original_swagger_file_path')

    # Initialize iteration counts and verbose flag if not already present
    state['current_iteration'] = state.get('current_iteration', 0)
    state['max_iterations'] = state.get('max_iterations', 5) # Default max iterations
    state['verbose'] = state.get('verbose', True) # Default to verbose

    if not file_path:
        state['error_message'] = "Input file path is missing."
        if state['verbose']: print(f"Error: {state['error_message']}")
        return state

    if not os.path.exists(file_path):
        state['error_message'] = f"Input file not found: {file_path}"
        if state['verbose']: print(f"Error: {state['error_message']}")
        return state

    content = None
    try:
        with open(file_path, 'r', encoding='utf-8') as f:
            file_content_str = f.read()

        try:
            # Try parsing as YAML first
            content = yaml.safe_load(file_content_str)
            if state['verbose']: print(f"Successfully parsed {file_path} as YAML.")
        except yaml.YAMLError as e_yaml:
            if state['verbose']: print(f"Failed to parse as YAML: {e_yaml}. Trying JSON...")
            try:
                # Try parsing as JSON if YAML fails
                content = json.loads(file_content_str)
                if state['verbose']: print(f"Successfully parsed {file_path} as JSON.")
            except json.JSONDecodeError as e_json:
                state['error_message'] = f"Failed to parse file as YAML or JSON: YAML error: {e_yaml}, JSON error: {e_json}"
                if state['verbose']: print(f"Error: {state['error_message']}")
                return state
    except Exception as e:
        state['error_message'] = f"Failed to read input file {file_path}: {str(e)}"
        if state['verbose']: print(f"Error: {state['error_message']}")
        return state

    if not isinstance(content, dict):
        state['error_message'] = "Parsed content is not a valid dictionary (JSON object)."
        if state['verbose']: print(f"Error: {state['error_message']}")
        return state

    state['swagger_content'] = content

    # Basic Swagger 2.0 validation
    if not content.get("swagger") == "2.0":
        state['error_message'] = "Invalid Swagger: 'swagger' field must be '2.0'."
        # Allow processing to continue to see if converter can handle it, but log error
        if state['verbose']: print(f"Validation Warning/Error: {state['error_message']}")
        # Not returning state here, as some tools might attempt conversion of slightly off versions.
        # The converter or linter will ultimately decide.
        # If strictness is required, this should return state.

    if not isinstance(content.get("info"), dict):
        state['error_message'] = (state.get('error_message') or "") + " Invalid Swagger: 'info' field must be an object. "
        if state['verbose']: print(f"Validation Warning/Error: 'info' field missing or not an object.")
        # Not returning, let converter try.

    if not isinstance(content.get("paths"), dict):
        state['error_message'] = (state.get('error_message') or "") + " Invalid Swagger: 'paths' field must be an object. "
        if state['verbose']: print(f"Validation Warning/Error: 'paths' field missing or not an object.")
        # Not returning, let converter try.

    if state.get('error_message'):
         print(f"Reader/Validator found issues: {state['error_message']}")
    elif state['verbose']:
        print("Swagger 2.0 file loaded and basic validation passed.")
        title = content.get("info", {}).get("title", "N/A")
        version = content.get("info", {}).get("version", "N/A")
        print(f"Title: {title}, Version: {version}")

    return state

def conversion_node(state: AppState) -> AppState:
    if state.get('verbose', True): print("--- Conversion Node ---")

    if state.get('error_message'): # If an error already exists from previous nodes
        if state.get('verbose', True): print("Skipping conversion due to existing error.")
        return state

    swagger_content = state.get('swagger_content')
    if not swagger_content or not isinstance(swagger_content, dict):
        state['error_message'] = "Swagger content is missing or invalid for conversion."
        if state.get('verbose', True): print(f"Error: {state['error_message']}")
        return state

    if state.get('verbose', True):
        print(f"Attempting conversion of Swagger 2.0 spec: {swagger_content.get('info', {}).get('title', 'Untitled')}")

    try:
        # The swagger-to-openapi library (by YAmfAR/Roman Hlevnoy) provides convert_from_dict
        # This was chosen based on the discussion in the prompt.
        converted_openapi_dict = swagger_to_openapi.convert_from_dict(swagger_content)

        state['openapi_content'] = converted_openapi_dict
        state['current_openapi_spec'] = converted_openapi_dict # Initialize for linting/correction cycle

        if state.get('verbose', True):
            print("Swagger 2.0 content successfully converted to OpenAPI 3.1.")
            # print(f"Converted OpenAPI version: {converted_openapi_dict.get('openapi')}")
            # print(f"Converted Info: {converted_openapi_dict.get('info', {}).get('title', 'Untitled')}")

    except Exception as e:
        error_msg = f"Failed to convert Swagger to OpenAPI: {str(e)}"
        state['error_message'] = error_msg
        if state.get('verbose', True): print(f"Error: {error_msg}")
        # Also print traceback for debugging if possible, or log it.
        import traceback
        if state.get('verbose', True): traceback.print_exc()

    return state

