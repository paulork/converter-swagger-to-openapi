def linting_node(state: AppState) -> AppState:
    verbose = state.get('verbose', True)
    if verbose: print(f"--- Linting Node (Iteration: {state.get('current_iteration', 0)}) ---")

    if state.get('error_message'):
        if verbose: print("Skipping linting due to existing error.")
        return state

    current_spec = state.get('current_openapi_spec')
    if not current_spec or not isinstance(current_spec, dict):
        state['error_message'] = "OpenAPI spec is missing or invalid for linting."
        if verbose: print(f"Error: {state['error_message']}")
        return state

    temp_file_path = None
    try:
        # Create a temporary file to store the spec for Redocly
        # Using NamedTemporaryFile to ensure it has a name for the subprocess
        with tempfile.NamedTemporaryFile(mode='w', delete=False, suffix='.yaml', encoding='utf-8') as tmpfile:
            yaml.dump(current_spec, tmpfile, sort_keys=False, default_flow_style=False)
            temp_file_path = tmpfile.name

        if verbose: print(f"OpenAPI spec written to temporary file: {temp_file_path}")

        # Construct Redocly CLI command
        # Use `npx redocly lint ...` to avoid global installation issues if possible,
        # or assume redocly is in PATH. For a controlled environment, `redocly` directly is fine.
        # The requirement `redocly` in `requirements.txt` should make it available in the environment.
        command = ["redocly", "lint", temp_file_path, "--format=json"]

        if verbose: print(f"Executing linting command: {' '.join(command)}")

        # Execute the command
        process = subprocess.run(command, capture_output=True, text=True, check=False) # check=False to handle non-zero exit codes ourselves

        if verbose:
            print(f"Redocly CLI exited with code: {process.returncode}")
            if process.stdout:
                print(f"Redocly stdout (first 500 chars): {process.stdout[:500]}")
            if process.stderr:
                print(f"Redocly stderr: {process.stderr}")

        # Redocly CLI typically exits with non-zero code if there are issues.
        # The JSON output is usually on stdout.
        # If stderr has content, it might be actual errors from Redocly tool or just warnings.

        if not process.stdout and process.returncode != 0:
            # If no stdout and non-zero exit code, it's likely a tool execution error
            error_detail = process.stderr or "No output from Redocly CLI."
            state['error_message'] = f"Redocly CLI execution failed. Exit code: {process.returncode}. Error: {error_detail}"
            if verbose: print(f"Error: {state['error_message']}")
            state['linter_issues'] = [] # Ensure it's an empty list on error
            return state

        if not process.stdout:
            # No output, assume no issues if exit code was 0.
            if verbose: print("Redocly CLI produced no output. Assuming no linting issues.")
            state['linter_issues'] = []
            return state

        try:
            # Attempt to parse stdout as JSON, this should contain the linting issues
            linter_issues_output = json.loads(process.stdout)

            # The structure of Redocly's JSON output needs to be known.
            # Typically, it's an array of issue objects, or an object with a key containing the array.
            # Example: { "problems": [...], "summary": {...} } or just [...]
            # For Redocly, if issues are found, it's an array of problem objects.
            # If no issues, it might be an empty array, or some summary object.
            # `redocly lint demo.yaml --format=json` when no errors gives:
            # { total: 0, critical: 0, error: 0, warn: 0, info: 0 }
            # And when there are errors:
            # [ { ruleId: 'operation-description', message: 'Operation `description` must be present and non-empty string.', location: '#/paths/~1pets/get', severity: 'error', suggestedFix: null, from: null } ]

            if isinstance(linter_issues_output, list):
                state['linter_issues'] = linter_issues_output
            elif isinstance(linter_issues_output, dict) and 'problems' in linter_issues_output and isinstance(linter_issues_output['problems'], list):
                state['linter_issues'] = linter_issues_output['problems'] # More robust for some linters
            elif isinstance(linter_issues_output, dict) and linter_issues_output.get('total', -1) == 0 : # Redocly specific for no issues
                state['linter_issues'] = []
            else:
                # Unexpected JSON structure
                state['error_message'] = "Redocly CLI returned unexpected JSON structure."
                if verbose: print(f"Warning: {state['error_message']} Output: {process.stdout[:500]}")
                state['linter_issues'] = [] # Or a generic error issue
                # Could also try to extract from a known structure if the above check is too simple.
                # For now, if it's not a list directly, or 'problems' list, or total:0 dict, assume unexpected.
                # If Redocly always returns a list for issues, the check can be simpler.
                # Based on documentation, if problems exist, it's an array. If not, it's an object with counts.

            if verbose:
                if state['linter_issues']:
                    print(f"Linting found {len(state['linter_issues'])} issues.")
                    # for issue in state['linter_issues'][:3]: # Print first few issues
                    #    print(f"  - {issue.get('ruleId', 'N/A')}: {issue.get('message', 'No message')}")
                else:
                    print("Linting complete. No issues found.")

        except json.JSONDecodeError:
            # If stdout is not JSON, it might be an error message from Redocly or something else.
            state['error_message'] = f"Failed to parse Redocly CLI output as JSON. Output: {process.stdout[:500]}"
            if verbose: print(f"Error: {state['error_message']}")
            state['linter_issues'] = []
            # Consider if stderr had more info if stdout parsing fails
            if process.stderr and verbose:
                print(f"Redocly stderr (relevant if stdout parsing failed): {process.stderr}")

    except FileNotFoundError:
        state['error_message'] = "Redocly CLI not found. Please ensure it is installed and in PATH."
        if verbose: print(f"Error: {state['error_message']}")
        state['linter_issues'] = []
    except Exception as e:
        state['error_message'] = f"An error occurred during linting: {str(e)}"
        if verbose:
            print(f"Error: {state['error_message']}")
            import traceback
            traceback.print_exc()
        state['linter_issues'] = []
    finally:
        # Clean up the temporary file
        if temp_file_path and os.path.exists(temp_file_path):
            try:
                os.remove(temp_file_path)
                if verbose: print(f"Temporary file {temp_file_path} deleted.")
            except Exception as e_del:
                if verbose: print(f"Warning: Could not delete temporary file {temp_file_path}: {e_del}")
                # Log this, but don't overwrite a more critical error_message
                if not state.get('error_message'):
                    state['error_message'] = f"Warning: Failed to delete temp file {temp_file_path}."

    return state

