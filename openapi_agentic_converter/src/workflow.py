def should_continue_correction(state: AppState) -> str:
    print(f"--- Condition: Should Continue Correction? (Iteration {state['current_iteration']}) ---")
    if state.get('error_message'):
        print("Error detected, stopping corrections.")
        return "end_workflow" # Or an error handling node

    if not state.get('linter_issues'):
        print("No linter issues found. Proceeding to best practices.")
        return "apply_best_practices"

    if state['current_iteration'] >= state.get('max_iterations', 5): # Max iterations check
        print(f"Max iterations ({state['max_iterations']}) reached. Proceeding despite remaining issues.")
        # Optionally, log a warning or set a flag here
        state['error_message'] = "Max iterations reached during correction. Issues might remain."
        return "apply_best_practices" # Or go to an error/warning summary node

    print(f"Linter issues exist and iterations ({state['current_iteration']}) < max ({state.get('max_iterations',5)}). Continuing correction.")
    return "correct_issues"

def check_for_errors(state: AppState) -> str:
    print("--- Condition: Check for errors ---")
    if state.get('error_message'):
        print(f"Error occurred: {state['error_message']}. Ending workflow.")
        return "end_workflow" # Or a dedicated error reporting node
    return "continue_workflow" # A general name for the next step if no specific branch

