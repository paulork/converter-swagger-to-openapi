# Define the state for the graph
class AppState(TypedDict):
    original_swagger_file_path: str # Path to the input Swagger 2.0 file
    swagger_content: Dict[str, Any] # Parsed Swagger 2.0 content
    openapi_content: Dict[str, Any] # Parsed OpenAPI 3.1 content (after conversion, before iteration)
    current_openapi_spec: Dict[str, Any] # OpenAPI spec being worked on by linter & corrector
    linter_issues: List[Dict[str, Any]] # List of issues from the linter
